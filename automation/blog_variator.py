# -*- coding: utf-8 -*-
import hashlib, datetime, re
from pathlib import Path

def diversify_blog_post():
    bp = Path('blog_post.txt')
    if not bp.exists(): return
    raw = bp.read_text(encoding='utf-8')
    m_memo = re.search(r'작업 메모\s*:\s*"(["]+)"', raw)
    m_reg = re.search(r'【([】]+)】', raw)
    memo = m_memo.group(1).strip() if m_memo else '현장 철거 및 폐기물 정리'
    region = m_reg.group(1).strip() if m_reg else '부산·경남'
    today = datetime.date.today().strftime('%Y.%m.%d')
    h = int(hashlib.md5((memo + today).encode('utf-8')).hexdigest(), 16)
    intros = [
        f'반갑습니다. 부산 사직동을 거점으로 {region} 현장을 직접 발로 뛰는 대봉개발입니다.\n오늘은 최근 다녀온 [{memo}] 현장 이야기와 함께, 작업 전 알아두시면 도움 되는 실무 기준을 정리해 드립니다.',
        f'안녕하세요! 30년 현장 노하우로 철거부터 폐기물 반출까지 직접 책임지는 대봉개발입니다.\n얼마 전 {region}에서 진행한 [{memo}] 작업을 마치고 돌아왔는데요. 현장 여건에 맞춘 진행 과정을 공유합니다.',
        f'{region} 일대에서 상가 원상복구나 폐기물 정리를 고민 중이신가요?\n하청 없이 직영 팀이 직접 현장을 챙기는 대봉개발에서 [{memo}] 시공 기록을 전해드립니다.',
        f'현장마다 구조도 다르고 반출 동선도 제각각이죠. {region} 지역 철거·폐기물 베테랑 대봉개발입니다.\n이번에 완료한 [{memo}] 현장을 바탕으로 깔끔한 정리 과정을 소개해 드릴게요.'
    ]
    bodies = [
        f'이번 {region} 현장은 사전 동선 파악이 무엇보다 중요했습니다. 주변 상가나 이웃에 불편을 주지 않도록 반출 경로를 먼저 확보한 뒤, 무거운 설비와 내부 구조물을 순서대로 안전하게 해체했습니다.\n\n특히 철거 작업은 단순히 부수는 것이 아니라 전기·수도·가스 마감 상태를 정확히 확인하고, 작업 후 바닥에 남는 잔해물까지 빗질하듯 깔끔하게 치워내는 것이 핵심입니다.',
        f'[{memo}] 작업을 진행하면서 가장 신경 쓴 부분은 안전과 신속한 반출이었습니다. 엘리베이터 유무와 차량 진입 여건을 미리 체크해 불필요한 시간 지체를 줄였습니다.\n\n현장에서 간혹 사진으로 미처 보이지 않던 숨은 구조물이나 추가 폐기물이 나오는 경우가 있는데요. 저희는 임의로 진행하지 않고 반드시 사진과 함께 먼저 상의드린 후 투명하게 처리하고 있습니다.',
        f'{region} 현장 도착 후 가장 먼저 철거 범위와 남겨두어야 할 시설물을 꼼꼼히 구분했습니다. 작업자 간 호흡이 잘 맞는 직영 베테랑 팀이 투입되어 철거부터 폐기물 상차까지 하루 만에 막힘없이 마무리했습니다.\n\n집기류만 부분 수거하는 작업부터 바닥·천장·가벽을 모두 비워내는 전체 원상복구까지 현장 상황에 딱 맞는 방식으로 진행해 드립니다.'
    ]
    qnas = [
        ('Q. 철거는 안 하고 내부 집기나 폐기물만 따로 치울 수도 있나요?', 'A. 물론입니다. 무거운 주방 설비, 사무용 가구, 대형 생활폐기물이나 마대 자루만 단독으로 수거하는 작업도 상시 진행하고 있습니다.'),
        ('Q. 일하느라 바쁜데 현장에 꼭 가 있어야 하나요?', 'A. 사전에 비워야 할 품목과 범위만 정확히 알려주시면, 작업 전·중·후 사진을 실시간으로 보내드리기 때문에 현장에 계시지 않아도 안심하고 맡기실 수 있습니다.'),
        ('Q. 방문 견적 전에 대략적인 비용을 먼저 알 수 있을까요?', 'A. 네, 010-8535-9787 번호로 [동네 이름 + 층수 + 현장 사진 몇 장]만 문자로 보내주시면 물량과 동선을 파악해 예상 견적을 빠르게 안내해 드립니다.'),
        ('Q. 임대인이 요구하는 원상복구 기준이 까다로운데 맞춰주실 수 있나요?', 'A. 30년 경력 동안 수많은 상가·식당·사무실 원상복구를 처리해 왔습니다. 가벽 철거부터 천장, 바닥 정리까지 임대차 계약 조건에 맞춰 깔끔하게 마감해 드립니다.')
    ]
    closings = [
        f'📍 {region} 및 부산·양산·김해 전 지역 상담 가능\n• 간편 문자 견적 : 동네 / 층수(계단·엘리베이터) / 현장 사진 전송\n• 직통 전화 : 010-8535-9787\n• 더 많은 현장 보기 : https://daebong-busan.kr/',
        f'📞 대봉개발 직통 상담 : 010-8535-9787\n문자(동네+층수+현장사진)를 남겨주시면 작업 중이라도 확인 즉시 친절히 안내해 드리겠습니다.\n공식 홈페이지(https://daebong-busan.kr/)에서도 다양한 지역별 작업 기록을 확인하실 수 있습니다.'
    ]
    q1 = qnas[h % len(qnas)]
    q2 = qnas[(h + 1) % len(qnas)]
    reg_tag = region.replace(' ', '')
    tags = [f'#{reg_tag}철거', f'#{reg_tag}폐기물', f'#{reg_tag}원상복구', '#부산철거', '#경남철거', '#상가원상복구', '#식당폐업정리', '#폐기물수거', '#대봉개발']
    new_post = f"{intros[h % len(intros)]}\n\n[{today} 현장 기록 : {memo}]\n\n{bodies[(h // 2) % len(bodies)]}\n\n💡 자주 묻는 질문 정리\n{q1[0]}\n{q1[1]}\n\n{q2[0]}\n{q2[1]}\n\n{closings[h % len(closings)]}\n\n{' '.join(tags)}"
    bp.write_text(new_post, encoding='utf-8')
    print('✓ 네이버 AI 유사문서 방지용 다변화 블로그 원고 생성 완료!')

if __name__ == '__main__':
    diversify_blog_post()
